@dataclass(frozen=True)
class _Page:
    number: int
    text: str
    no_text: bool


@dataclass(frozen=True)
class _Sentence:
    """A sentence (or heading) located by offsets in its page text."""

    page: int
    start: int
    end: int
    page_text: str = field(repr=False)
    heading: str | None
    is_heading: bool

    @property
    def text(self) -> str:
        return self.page_text[self.start : self.end]

    @property
    def clean(self) -> str:
        """Whitespace-collapsed text without a leading list marker (for display fields)."""
        collapsed = " ".join(self.text.split())
        return _LIST_START_RE.sub("", collapsed, count=1) or collapsed

    @property
    def word_count(self) -> int:
        return len(self.text.split())


class _Document:
    """The parsed pages and sentences of one request's document context."""

    def __init__(self, document_context: str) -> None:
        self.pages = _parse_pages(document_context)
        self._word_spans = {
            page.number: [m.span() for m in _WORD_RE.finditer(page.text)] for page in self.pages
        }
        self.sentences = _segment(self.pages)
        self.body = [s for s in self.sentences if not s.is_heading and s.word_count >= 3]

    @property
    def no_text_pages(self) -> list[int]:
        return [p.number for p in self.pages if p.no_text]

    def quote(self, sentence: _Sentence, focus: int | None = None) -> SourceQuote:
        """An exact substring of the page text, 5-25 words, trimmed at word boundaries.

        Long sentences are windowed around ``focus`` (a page-text offset); sentences shorter
        than five words are extended with the words that follow them on the page.
        """
        spans = self._word_spans[sentence.page]
        starts = [s for s, _ in spans]
        first = bisect.bisect_left(starts, sentence.start)
        last = bisect.bisect_right(starts, sentence.end - 1) - 1
        text = sentence.page_text
        if last - first + 1 > _MIN_QUOTE_WORDS and _LIST_TOKEN_RE.match(text[slice(*spans[first])]):
            first += 1
        count = last - first + 1
        if count < _MIN_QUOTE_WORDS:
            last = min(len(spans) - 1, first + _MIN_QUOTE_WORDS - 1)
            first = max(0, last - _MIN_QUOTE_WORDS + 1)
        elif count > _MAX_QUOTE_WORDS:
            anchor = first
            if focus is not None:
                anchor = max(first, min(last, bisect.bisect_right(starts, focus) - 1))
            first = max(first, min(anchor - 8, last - _MAX_QUOTE_WORDS + 1))
            last = first + _MAX_QUOTE_WORDS - 1
        quote = text[spans[first][0] : spans[last][1]]
        trimmed = quote.rstrip(",;:(")
        return SourceQuote(page=sentence.page, quote=trimmed or quote)


