# --- Parsing ---------------------------------------------------------------------------------


def _unescape(text: str) -> str:
    for entity, char in _ENTITIES:
        text = text.replace(entity, char)
    return text.replace("&amp;", "&")


def _parse_pages(document_context: str) -> list[_Page]:
    pages: list[_Page] = []
    for index, match in enumerate(_PAGE_RE.finditer(document_context), start=1):
        attrs = {
            m.group(1).lower(): next(g for g in m.groups()[1:] if g is not None)
            for m in _ATTR_RE.finditer(match.group("attrs"))
        }
        number_attr = attrs.get("number", "").strip()
        number = int(number_attr) if number_attr.isdigit() else index
        if any(page.number == number for page in pages):
            continue  # malformed input: keep the first page with a given number
        text = _unescape(match.group("body") or "")
        no_text = attrs.get("status", "").lower() in _NO_TEXT_STATUSES or not text.strip()
        pages.append(_Page(number=number, text=text, no_text=no_text))
    return pages


def _question(instruction: str) -> str:
    match = _QUESTION_RE.search(instruction)
    raw = match.group("q") if match else _TAG_RE.sub(" ", instruction)
    return " ".join(_unescape(raw).split())


# --- Segmentation ----------------------------------------------------------------------------


def _is_heading(line: str) -> bool:
    words = line.split()
    if len(words) > 8 or line[-1] in ".!?;,":
        return False
    if _NORMATIVE_RE.search(line) or _RISK_LABEL_RE.match(line):
        return False
    letters = [c for c in line if c.isalpha()]
    if not letters:
        return False
    if all(c.isupper() for c in letters):
        return True
    return bool(_NUMBERED_HEADING_RE.match(line)) and len(words) <= 5


def _segment(pages: list[_Page]) -> list[_Sentence]:
    """Split pages into headings and sentences, tracking the current section heading."""
    sentences: list[_Sentence] = []
    heading: str | None = None
    for page in pages:
        if page.no_text:
            continue
        for start, end, is_heading in _segment_page(page.text):
            if is_heading:
                heading = " ".join(page.text[start:end].split())
            sentences.append(
                _Sentence(
                    page=page.number,
                    start=start,
                    end=end,
                    page_text=page.text,
                    heading=heading,
                    is_heading=is_heading,
                )
            )
    return sentences


def _segment_page(text: str) -> list[tuple[int, int, bool]]:
    """Return ``(start, end, is_heading)`` spans of headings and sentences in ``text``."""
    spans: list[tuple[int, int, bool]] = []
    block: list[int] = []  # [start, end] of the paragraph being collected

    def close_block() -> None:
        if block:
            spans.extend((s, e, False) for s, e in _split_sentences(text, block[0], block[1]))
            block.clear()

    previous_end = 0
    for match in re.finditer(r"[^\n]+", text):
        line = match.group()
        stripped = line.strip()
        blank_gap = text.count("\n", previous_end, match.start()) >= 2
        previous_end = match.end()
        if not stripped:
            close_block()
            continue
        start = match.start() + len(line) - len(line.lstrip())
        end = match.start() + len(line.rstrip())
        if _is_heading(stripped):
            close_block()
            spans.append((start, end, True))
            continue
        if blank_gap or _LIST_START_RE.match(stripped) or _RISK_LABEL_RE.match(stripped):
            close_block()
        if block:
            block[1] = end
        else:
            block.extend((start, end))
    close_block()
    return spans


def _split_sentences(text: str, start: int, end: int) -> list[tuple[int, int]]:
    chunk = text[start:end]
    pieces: list[tuple[int, int]] = []
    position = 0
    for boundary in _SENTENCE_BOUNDARY_RE.finditer(chunk):
        before = chunk[position : boundary.start()].split()
        if before and before[-1].lower() in _ABBREVIATIONS:
            continue
        # "1. Check ..." — a leading list number is not a sentence of its own.
        if len(before) == 1 and _LIST_NUMBER_RE.match(before[0]):
            continue
        pieces.append((position, boundary.start()))
        position = boundary.end()
    pieces.append((position, len(chunk)))
    return [(start + s, start + e) for s, e in pieces if chunk[s:e].strip()]


# --- Task builders ---------------------------------------------------------------------------


def _obligation(text: str) -> tuple[Obligation, re.Match[str]] | None:
    """The strongest normative keyword in ``text`` and its obligation level."""
    for obligation, pattern in _OBLIGATIONS:
        match = pattern.search(text)
        if match:
            return obligation, match
    return None


def _category(text: str) -> str | None:
    return next((name for name, pattern in _CATEGORIES if pattern.search(text)), None)


def _requirements(doc: _Document) -> tuple[list[LLMRequirement], list[str]]:
    found: list[LLMRequirement] = []
    for sentence in doc.body:
        result = _obligation(sentence.text)
        if result is None:
            continue
        obligation, match = result
        # "Failure may cause injury" describes a risk, not a permission.
        if obligation == "permitted" and _RISK_RE.search(sentence.text):
            continue
        found.append(
            LLMRequirement(
                statement=sentence.clean,
                basis="explicit",
                obligation=obligation,
                category=_category(sentence.text),
                sources=[doc.quote(sentence, sentence.start + match.start())],
            )
        )
    return _capped(found, "requirements")


def _specifications(doc: _Document) -> tuple[list[LLMSpecification], list[str]]:
    found: list[LLMSpecification] = []
    seen: set[tuple[str, str, str | None]] = set()
    for sentence in doc.body:
        text = sentence.text
        previous_end = 0
        parameter = ""
        matches = [(m, m.group("unit")) for m in _SPEC_RE.finditer(text)]
        matches += [(m, "pH") for m in _PH_RE.finditer(text)]
        for match, unit in sorted(matches, key=lambda item: item[0].start()):
            parameter = _parameter(text, previous_end, match.start()) or parameter
            previous_end = match.end()
            name = parameter or _first_words(sentence.clean, 4)
            value = match.group("value").strip()
            key = (name.lower(), value, unit)
            if key in seen:
                continue
            seen.add(key)
            found.append(
                LLMSpecification(
                    parameter=name,
                    value=value,
                    unit=unit,
                    context=sentence.heading,
                    sources=[doc.quote(sentence, sentence.start + match.start())],
                )
            )
    return _capped(found, "specifications")


def _parameter(text: str, lower: int, upper: int) -> str:
    """The words naming a value, e.g. 'Hydraulic oil temperature' in '... shall be 40-60 °C'."""
    segment = text[lower:upper]
    cut = max(segment.rfind(c) for c in ",;:(")
    words = _PARAM_WORD_RE.findall(segment[cut + 1 :])
    while words and words[-1].lower() in _PARAM_STOPWORDS:
        words.pop()
    words = words[-4:]
    while words and words[0].lower() in _PARAM_STOPWORDS:
        words.pop(0)
    phrase = " ".join(words)
    return phrase[:1].upper() + phrase[1:]


def _risks(doc: _Document) -> tuple[list[LLMRisk], list[str]]:
    found: list[LLMRisk] = []
    for sentence in doc.body:
        match = _RISK_RE.search(sentence.text)
        if match is None:
            continue
        found.append(
            LLMRisk(
                title=_risk_title(sentence),
                description=sentence.clean,
                severity=_severity(sentence.text),
                basis="explicit",
                sources=[doc.quote(sentence, sentence.start + match.start())],
            )
        )
    return _capped(found, "risks")


def _severity(text: str) -> Severity:
    if _HIGH_SEVERITY_RE.search(text):
        return "high"
    if _MEDIUM_SEVERITY_RE.search(text):
        return "medium"
    return "low"


def _risk_title(sentence: _Sentence) -> str:
    text = sentence.clean
    label = _RISK_LABEL_RE.match(text)
    if label and label.group("label").lower() in _SAFETY_LABELS:
        rest = _first_words(text[label.end() :], 7)
        return f"{label.group('label').capitalize()}: {rest}" if rest else text
    return _first_words(text, 8)


def _actions(risks: list[LLMRisk]) -> list[LLMAction]:
    """Two or three generic, inferred actions derived from the risks that were found."""
    if not risks:
        return []
    high = [r for r in risks if r.severity == "high"]
    actions: list[LLMAction] = []
    if high:
        actions.append(
            LLMAction(
                action=(
                    "Confirm that everyone performing this procedure is trained on the "
                    "high-severity hazards it identifies."
                ),
                rationale=(
                    f"The document names {len(high)} high-severity risk statement(s), "
                    f"for example: {high[0].title}."
                ),
                priority="high",
                basis="inferred",
                sources=list(high[0].sources),
            )
        )
    actions.append(
        LLMAction(
            action="Check that the warnings and cautions in this document are visible at the "
            "point of use.",
            rationale=f"The document contains {len(risks)} risk-related statement(s).",
            priority="medium",
            basis="inferred",
            sources=list(risks[0].sources),
        )
    )
    if len(risks) > 1:
        actions.append(
            LLMAction(
                action="Review the identified risks with the document owner at the next "
                "periodic review.",
                rationale=f"Risks are described in several places, for example: {risks[-1].title}.",
                priority="low",
                basis="inferred",
                sources=list(risks[-1].sources),
            )
        )
    return actions


def _summarize(doc: _Document) -> LLMSummarizeOutput:
    requirements, req_notes = _requirements(doc)
    specifications, spec_notes = _specifications(doc)
    risks, risk_notes = _risks(doc)
    limitations = _limitations(doc, req_notes + spec_notes + risk_notes)

    candidates = [s for s in doc.body if s.word_count >= _MIN_QUOTE_WORDS]
    if not candidates:
        summary = LLMSummary(
            purpose="The document contains no extractable text to summarize.",
            executive=LLMExecutiveSummary(
                text="No text could be analyzed, so no summary was produced. "
                "Review the source document directly.",
                sources=[],
            ),
            key_points=[],
        )
        return LLMSummarizeOutput(
            summary=summary,
            requirements=[],
            specifications=[],
            risks=[],
            actions=[],
            limitations=limitations,
        )

    intro = _intro(candidates)
    purpose = intro[0]

    mandatory = sum(1 for r in requirements if r.obligation == "mandatory")
    overview = (
        f"The document contains {len(requirements)} requirement statement(s) "
        f"({mandatory} mandatory), {len(specifications)} specified value(s) and "
        f"{len(risks)} risk-related statement(s)."
    )
    executive = LLMExecutiveSummary(
        text=" ".join([*(_as_sentence(s.clean) for s in intro), overview]),
        sources=[doc.quote(s) for s in intro],
    )
    summary = LLMSummary(
        purpose=purpose.clean,
        executive=executive,
        key_points=_key_points(doc, requirements, risks, exclude=intro),
    )
    return LLMSummarizeOutput(
        summary=summary,
        requirements=requirements,
        specifications=specifications,
        risks=risks,
        actions=_actions(risks),
        limitations=limitations,
    )


def _intro(candidates: list[_Sentence]) -> list[_Sentence]:
    """Purpose (and scope) sentences from the first page with text; else its first sentence."""
    first_page = candidates[0].page
    purposeful = [
        s
        for s in candidates
        if s.page == first_page
        and (
            _PURPOSE_TEXT_RE.search(s.text)
            or (s.heading is not None and _PURPOSE_HEADING_RE.search(s.heading))
        )
    ]
    return purposeful[:2] or [candidates[0]]


def _key_points(
    doc: _Document,
    requirements: list[LLMRequirement],
    risks: list[LLMRisk],
    *,
    exclude: list[_Sentence],
) -> list[LLMKeyPoint]:
    points: list[LLMKeyPoint] = []
    seen = {s.clean for s in exclude}
    mandatory = [r for r in requirements if r.obligation == "mandatory"]
    ranked = sorted(risks, key=lambda r: ("high", "medium", "low").index(r.severity))
    for text, sources in [
        *((r.statement, r.sources) for r in mandatory[:3]),
        *((r.description, r.sources) for r in ranked[:2]),
    ]:
        if text not in seen and len(points) < _MAX_KEY_POINTS:
            seen.add(text)
            points.append(LLMKeyPoint(text=text, sources=list(sources)))
    for sentence in doc.body:
        if len(points) >= 3:
            break
        if sentence.word_count >= _MIN_QUOTE_WORDS and sentence.clean not in seen:
            seen.add(sentence.clean)
            points.append(LLMKeyPoint(text=sentence.clean, sources=[doc.quote(sentence)]))
    return points


def _answer(doc: _Document, question: str) -> LLMAnswerOutput:
    keywords = {_normalize(t) for t in _ASK_TOKEN_RE.findall(question.lower())}
    keywords = {k for k in keywords if len(k) >= 3 and k not in _ASK_STOPWORDS}

    scored: list[tuple[int, int, _Sentence, int]] = []
    for order, sentence in enumerate(doc.body):
        tokens = list(_ASK_TOKEN_RE.finditer(sentence.text))
        hits = [t for t in tokens if _normalize(t.group().lower()) in keywords]
        overlap = len({_normalize(t.group().lower()) for t in hits})
        if overlap:
            scored.append((-overlap, order, sentence, sentence.start + hits[0].start()))
    scored.sort(key=lambda item: (item[0], item[1]))

    if not scored:
        candidates = [s for s in doc.body if s.word_count >= _MIN_QUOTE_WORDS]
        answer = "The document does not appear to contain information about this question."
        if candidates:
            answer += f" It covers: {_as_sentence(_intro(candidates)[0].clean)}"
        return LLMAnswerOutput(answerable=False, answer=answer, sources=[])

    best = -scored[0][0]
    chosen = [item for item in scored[:2] if -item[0] * 2 >= best]
    chosen.sort(key=lambda item: item[1])  # document order
    return LLMAnswerOutput(
        answerable=True,
        answer="According to the document: " + " ".join(item[2].clean for item in chosen),
        sources=[doc.quote(item[2], item[3]) for item in chosen],
    )


# --- Helpers ---------------------------------------------------------------------------------


def _normalize(token: str) -> str:
    return token[:-1] if len(token) > 3 and token.endswith("s") else token


def _as_sentence(text: str) -> str:
    return text if text.endswith((".", "!", "?")) else f"{text}."


def _first_words(text: str, count: int) -> str:
    return " ".join(text.split()[:count]).rstrip(".,;:!?")


def _capped(items: list[_T], label: str) -> tuple[list[_T], list[str]]:
    if len(items) <= MAX_ITEMS:
        return items, []
    return items[:MAX_ITEMS], [
        f"Only the first {MAX_ITEMS} of {len(items)} {label} found are listed."
    ]


def _limitations(doc: _Document, notes: list[str]) -> list[str]:
    limitations = [_DEV_LIMITATION]
    if not doc.pages:
        limitations.append("No page content was provided.")
    elif doc.no_text_pages:
        pages = ", ".join(str(n) for n in doc.no_text_pages)
        limitations.append(f"Page(s) {pages} had no extractable text and were not analyzed.")
    limitations.extend(notes)
    return limitations
